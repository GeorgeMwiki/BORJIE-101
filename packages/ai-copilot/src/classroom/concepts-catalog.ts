/**
 * Mining-estate concept catalog (Wave 11 + Wave 13 expansion).
 *
 * BORJIE's AI Professor / Consultant sub-personas use this catalog to
 * teach the operator / employee / owner — from single-PML artisanal miner up
 * to multi-licence institutional mining groups. Concepts form a DAG: each
 * concept lists prerequisites that should be mastered first.
 *
 * The catalog is intentionally flat data (pure). Runtime classroom modules
 * consume it without mutating. Each concept also carries a numeric
 * difficulty rating (1-5) plus 3-5 worked examples grounded in East African
 * markets so the Professor can cite them by name and the Consultant can
 * pattern-match on real numbers.
 */

export interface WorkedExample {
  readonly id: string;
  readonly title: string;
  readonly market: 'TZ' | 'KE' | 'UG' | 'RW' | 'global';
  readonly inputs: string;
  readonly calculation: string;
  readonly answer: string;
}

export interface Concept {
  readonly id: string;
  readonly titleEn: string;
  readonly titleSw: string;
  readonly summaryEn: string;
  readonly summarySw: string;
  readonly category:
    | 'financial'
    | 'tenancy'
    | 'compliance'
    | 'maintenance'
    | 'operations'
    | 'strategy';
  readonly prerequisites: readonly string[];
  readonly bloomLevels: readonly (
    | 'remember'
    | 'understand'
    | 'apply'
    | 'analyze'
    | 'evaluate'
    | 'create'
  )[];
  readonly difficulty: 'beginner' | 'intermediate' | 'advanced';
  /** Numeric difficulty 1 (easiest) to 5 (hardest). */
  readonly difficultyRank: 1 | 2 | 3 | 4 | 5;
  readonly workedExamples: readonly WorkedExample[];
}

